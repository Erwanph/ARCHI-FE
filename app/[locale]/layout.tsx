import type { Metadata, Viewport } from 'next';
import { preload } from 'react-dom';
import { AnalyticsRuntime } from '@/components/analytics-runtime';
import { BoundaryCopyProvider } from '@/components/boundary-copy';
import { IntroLoader } from '@/components/intro-loader';
import { MotionProvider } from '@/components/motion/motion-provider';
import { NusaLauncher } from '@/components/nusa/nusa-launcher';
import { SiteFooter } from '@/components/site-footer';
import { SiteHeader } from '@/components/site-header';
import { WhatsAppTab } from '@/components/whatsapp-tab';
import { whatsappHref } from '@/lib/business-profile';
import { localeMeta, localizePath, locales } from '@/lib/i18n/config';
import { getDictionary, resolveLocale } from '@/lib/i18n/get-dictionary';
import { languageAlternates } from '@/lib/i18n/metadata';
import { SITE_NAME, SITE_ORIGIN } from '@/lib/site';
import '../globals.css';

export function generateStaticParams() {
  return locales.map((locale) => ({ locale }));
}

export async function generateMetadata({
  params,
}: {
  params: Promise<{ locale: string }>;
}): Promise<Metadata> {
  const locale = await resolveLocale(params);
  const dict = await getDictionary(locale);
  return {
    metadataBase: new URL(SITE_ORIGIN),
    title: { default: dict.meta.siteTitle, template: '%s | ARCHI' },
    description: dict.meta.siteDescription,
    alternates: languageAlternates(locale, '/'),
    // The "A" of the ARCHI wordmark (generated by `npm run icons`).
    icons: {
      icon: [
        { url: '/favicon.ico', sizes: '16x16 32x32 48x48' },
        { url: '/icon-192.png', type: 'image/png', sizes: '192x192' },
        { url: '/icon-512.png', type: 'image/png', sizes: '512x512' },
      ],
      apple: [{ url: '/apple-touch-icon.png', sizes: '180x180' }],
    },
    openGraph: {
      title: dict.meta.siteTitle,
      description: dict.meta.siteDescription,
      url: localizePath(locale, '/'),
      siteName: SITE_NAME,
      locale: localeMeta[locale].htmlLang.replace('-', '_'),
      type: 'website',
      images: [{ url: '/og.png', width: 1200, height: 630, alt: dict.meta.siteTitle }],
    },
    twitter: {
      card: 'summary_large_image',
      title: dict.meta.siteTitle,
      description: dict.meta.siteDescription,
      images: ['/og.png'],
    },
  };
}

export const viewport: Viewport = {
  themeColor: '#163829',
};

const criticalFonts = [
  '/fonts/eb-garamond-400.woff2',
  '/fonts/eb-garamond-500-italic.woff2',
  '/fonts/lato-400.woff2',
  '/fonts/lato-700.woff2',
];

export default async function RootLayout({
  children,
  params,
}: Readonly<{
  children: React.ReactNode;
  params: Promise<{ locale: string }>;
}>) {
  const locale = await resolveLocale(params);
  const dict = await getDictionary(locale);
  const meta = localeMeta[locale];

  criticalFonts.forEach((href) =>
    preload(href, { as: 'font', type: 'font/woff2', crossOrigin: 'anonymous' }),
  );

  const organizationJsonLd = {
    '@context': 'https://schema.org',
    '@type': 'Organization',
    name: SITE_NAME,
    url: SITE_ORIGIN,
    logo: `${SITE_ORIGIN}/brand/archi-wordmark-green.png`,
    description: dict.meta.siteDescription,
  };
  const websiteJsonLd = {
    '@context': 'https://schema.org',
    '@type': 'WebSite',
    name: SITE_NAME,
    url: SITE_ORIGIN,
    inLanguage: meta.htmlLang,
    description: dict.meta.siteDescription,
  };

  return (
    <html lang={meta.htmlLang} dir={meta.dir} suppressHydrationWarning>
      <body>
        <IntroLoader label={dict.intro.loading} />
        <noscript>
          {/* Scroll reveals start hidden; keep content visible without JS. */}
          <style>{`[data-reveal]{opacity:1!important;transform:none!important;clip-path:none!important}`}</style>
        </noscript>
        <a
          href="#main-content"
          className="fixed top-3 left-3 z-[100] -translate-y-[180%] rounded-full bg-sand px-4 py-2.5 text-xs font-bold text-forest transition-transform focus:translate-y-0"
        >
          {dict.common.skipToContent}
        </a>
        <MotionProvider>
          <SiteHeader
            locale={locale}
            copy={{ nav: dict.nav, common: dict.common, language: dict.language }}
          />
          <main id="main-content" tabIndex={-1} className="outline-none">
            <BoundaryCopyProvider value={{ locale, error: dict.error, notFound: dict.notFound }}>
              {children}
            </BoundaryCopyProvider>
          </main>
          <SiteFooter locale={locale} dict={dict} />
          <WhatsAppTab copy={dict.whatsapp} />
          <NusaLauncher
            locale={locale}
            copy={dict.nusa}
            whatsappHref={whatsappHref(dict.whatsapp.prefill)}
            contactHref={localizePath(locale, '/contact')}
          />
        </MotionProvider>
        <AnalyticsRuntime />
        <script
          type="application/ld+json"
          dangerouslySetInnerHTML={{
            __html: JSON.stringify([organizationJsonLd, websiteJsonLd]).replace(/</g, '\\u003c'),
          }}
        />
      </body>
    </html>
  );
}
